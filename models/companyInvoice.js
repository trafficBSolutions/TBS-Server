const mongoose = require('mongoose');

const companyInvoiceSchema = new mongoose.Schema({
  company: { type: String, required: true, index: true },
  invoiceNumber: { type: String },
  sentAt: { type: Date, default: Date.now },
  sentTo: { type: String },
  additionalEmails: [{ type: String }],
  payStatus: { type: String, enum: ['paid', 'unpaid'], default: 'unpaid' },
  payMethod: { type: String },
  lineItems: [{
    _id: false,
    description: { type: String },
    officerAb: { type: String },
    abSignsLights: { type: String },
    mileage: { type: String },
    extra: { type: String },
    amount: { type: Number, default: 0 },
  }],
  invoicePdfName: { type: String },
  invoicePdfData: { type: Buffer },
  workOrderPdfName: { type: String },
  workOrderPdfData: { type: Buffer },
  remitName: { type: String },
  remitData: { type: Buffer },
  // Historical ledger fields
  isHistorical: { type: Boolean, default: false },
  dateBilled: { type: Date },
  dueDate: { type: Date },
  amount: { type: Number },
  streetNum: { type: String },
  streetName: { type: String },
  city: { type: String },
  state: { type: String },
  workOrder: { type: String },
  coordinator: { type: String },
  amountReceived: { type: Number },
  dateOfDeposit: { type: Date },
  ckOrEft: { type: String },
  checkOrEftDate: { type: Date },
  officerOrAb: { type: String },
  abSignsLightsCones: { type: String },
  mileage: { type: String },
  extra: { type: String },
}, { timestamps: true });

module.exports = mongoose.model('CompanyInvoice', companyInvoiceSchema);
